/*
 * Server dashboard: subscribes to /api/metrics/stream (Server-Sent Events,
 * one JSON snapshot per second) and draws tiles, two small SVG charts,
 * the open-socket table and the event log.
 */

import { $, el, avatar, formatBytes, formatDuration } from "./utils.js";

// Follow the theme chosen in the chat app (stored in localStorage).
try {
  const theme = JSON.parse(localStorage.getItem("hs:theme") || '"auto"');
  if (theme !== "auto") document.documentElement.dataset.theme = theme;
} catch { /* ignore */ }

const SVG_NS = "http://www.w3.org/2000/svg";
const hover = { rate: null, bytes: null }; // index under the mouse, kept across re-renders
let latest = null;
let lastLogKey = "";

// ---------------------------------------------------------------- join ---

// QR codes: the app on this Wi-Fi, the CA certificate iPhones install once,
// and (only with --share) the public tunnel address for people anywhere.
let join = {};
let qrShown = "join";

function showQr(which) {
  const options = {
    join: [join.qr_svg, join.url || location.origin],
    cert: [join.cert_qr_svg, join.cert_url],
    remote: [join.public_qr_svg, join.public_url],
  };
  const pick = options[which] && options[which][0] ? which : "join";
  const [svg, text] = options[pick];
  qrShown = pick;
  $("#qr").innerHTML = svg || ""; // SVG generated by our own server
  $("#join-url").textContent = text || "";
  document.querySelectorAll("#qr-tabs button").forEach((b) => b.classList.toggle("active", b.dataset.qr === qrShown));
}

function loadJoin() {
  fetch("/api/join").then((r) => r.json()).then((data) => {
    join = data;
    $('[data-qr="remote"]').hidden = !join.public_url;
    $("#qr-tabs").hidden = !join.cert_qr_svg && !join.public_url;
    showQr(qrShown);
  });
}
document.querySelectorAll("#qr-tabs button").forEach((b) => b.addEventListener("click", () => showQr(b.dataset.qr)));
loadJoin();

// -------------------------------------------------------------- stream ---

function connect() {
  const es = new EventSource("/api/metrics/stream");
  es.onopen = () => setLive(true);
  es.onmessage = (e) => {
    latest = JSON.parse(e.data);
    render(latest);
  };
  es.onerror = () => setLive(false); // EventSource retries by itself
}
connect();

function setLive(on) {
  $("#live").classList.toggle("on", on);
  $("#live-text").textContent = on ? "Live" : "Reconnecting…";
}

window.addEventListener("resize", () => latest && render(latest));

// -------------------------------------------------------------- render ---

function render(s) {
  $("#uptime").textContent = formatDuration(s.uptime_s);
  if (s.server.public_url && !join.public_url) loadJoin(); // the tunnel came up after the page loaded

  // network facts
  const facts = [
    ["Server IP", s.server.ip || "-"],
    ["Port", s.server.port || "-"],
    ["Address type", s.server.private_ip ? "Private (DHCP, behind NAT)" : "Public / other"],
    ["Transport", s.server.scheme === "https" ? "TCP + TLS" : "TCP (no TLS)"],
    ["Remote access", s.server.public_url ? "On (Cloudflare tunnel)" : "Off (Wi-Fi only)"],
  ];
  $("#net-facts").replaceChildren(...facts.map(([k, v]) => el("li", {}, el("span", { text: k }), el("span", { class: "mono", text: String(v) }))));

  // tiles
  const c = s.connections;
  $("#t-conns").textContent = c.total;
  const split = $("#t-split");
  split.children[0].style.flexGrow = c.ws;
  split.children[1].style.flexGrow = c.sse;
  $("#t-split-text").textContent = `${c.ws} WebSocket · ${c.sse} HTTP/SSE`;
  $("#t-users").textContent = s.online_users.length;
  $("#t-users").title = s.online_users.join(", ") || "nobody yet";

  // Average round trip over the phones that reported one (heartbeat PING/PONG).
  const rtts = s.connection_list.map((x) => x.rtt_ms).filter((x) => x !== null && x !== undefined).map(Number);
  $("#t-rtt").textContent = rtts.length ? `${(rtts.reduce((a, b) => a + b, 0) / rtts.length).toFixed(1)} ms` : "-";
  $("#t-rtt-sub").textContent = rtts.length
    ? `best ${Math.min(...rtts).toFixed(1)} · worst ${Math.max(...rtts).toFixed(1)} ms · ${rtts.length} phone${rtts.length === 1 ? "" : "s"}`
    : "waiting for the first heartbeat";
  $("#t-rate").textContent = s.rates_now.messages_per_s;
  $("#t-peak").textContent = Math.max(0, ...s.history.map((h) => h.messages));
  const bps = s.rates_now.bytes_in_per_s + s.rates_now.bytes_out_per_s;
  $("#t-bps").textContent = `${formatBytes(bps)}/s`;
  $("#t-bps").title = `total ${formatBytes(s.totals.bytes_in)} in · ${formatBytes(s.totals.bytes_out)} out`;
  $("#t-total").textContent = s.messages.total_stored;
  $("#t-by-proto").textContent = `since start: ${s.messages.by_protocol.ws || 0} WS · ${s.messages.by_protocol.http || 0} HTTP`;
  $("#t-proc").textContent = s.processing_ms.avg === null ? "-" : `${s.processing_ms.avg.toFixed(2)} ms`;
  $("#t-proc").title = s.processing_ms.p95 === null ? "validate + store + queue" : `p95 ${s.processing_ms.p95.toFixed(2)} ms`;
  $("#t-dups").textContent = s.messages.duplicates_rejected;
  $("#t-errors").textContent = s.errors;

  // charts (pad to 60 slots so the x-axis is stable)
  const history = [...Array(Math.max(0, 60 - s.history.length)).fill(null), ...s.history];
  const times = history.map((h) => (h ? h.t : ""));
  drawBars($("#chart-rate"), history.map((h) => (h ? h.messages : 0)), times, "rate");
  drawLines($("#chart-bytes"), [
    { name: "Bytes in", cls: "s1", values: history.map((h) => (h ? h.bytes_in : 0)) },
    { name: "Bytes out", cls: "s2", values: history.map((h) => (h ? h.bytes_out : 0)) },
  ], times, "bytes");
  renderTables(s.history);

  renderConnections(s);
  renderLog(s.events);
}

// --------------------------------------------------------- chart helpers ---

/** Top of the y-axis: 4 gridline steps, each step a "round" 1, 2 or 5 x 10^k. */
function niceMax(value) {
  const raw = Math.max(value, 4) / 4;
  const pow = 10 ** Math.floor(Math.log10(raw));
  for (const step of [1, 2, 5, 10]) if (step * pow >= raw) return step * pow * 4;
  return 40 * pow;
}

function svg(tag, attrs = {}) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  return node;
}

/** Shared frame: y gridlines + labels, x labels. Returns geometry. */
function frame(container, maxValue, times, formatY) {
  const width = container.clientWidth || 600;
  const height = container.clientHeight || 210;
  const m = { left: 52, right: 64, top: 10, bottom: 22 };
  const plotW = width - m.left - m.right;
  const plotH = height - m.top - m.bottom;
  const root = svg("svg", { viewBox: `0 0 ${width} ${height}`, role: "img" });
  const yMax = niceMax(maxValue);

  for (let i = 0; i <= 4; i++) {
    const v = (yMax / 4) * i;
    const y = m.top + plotH - (v / yMax) * plotH;
    root.append(svg("line", { class: "gridline", x1: m.left, x2: m.left + plotW, y1: y, y2: y }));
    const label = svg("text", { class: "axis-label", x: m.left - 8, y: y + 4, "text-anchor": "end" });
    label.textContent = formatY(v);
    root.append(label);
  }
  const n = times.length;
  for (const i of [0, Math.floor(n / 2), n - 1]) {
    const text = svg("text", {
      class: "axis-label", x: m.left + (plotW * (i + 0.5)) / n, y: height - 4,
      "text-anchor": i === 0 ? "start" : i === n - 1 ? "end" : "middle",
    });
    text.textContent = i === n - 1 ? "now" : `-${n - 1 - i}s`;
    root.append(text);
  }
  container.replaceChildren(root);
  const x = (i) => m.left + (plotW * (i + 0.5)) / n;
  const y = (v) => m.top + plotH - (v / yMax) * plotH;
  return { root, m, plotW, plotH, n, x, y };
}

function showTooltip(event, html) {
  const tip = $("#tooltip");
  tip.replaceChildren(...html);
  tip.classList.add("show");
  const pad = 14;
  let left = event.clientX + pad;
  if (left + tip.offsetWidth > innerWidth - 8) left = event.clientX - tip.offsetWidth - pad;
  tip.style.left = `${left}px`;
  tip.style.top = `${Math.max(8, event.clientY - tip.offsetHeight - pad)}px`;
}
function hideTooltip() { $("#tooltip").classList.remove("show"); }

/** Single-series bar chart with rounded tops anchored to the baseline. */
function drawBars(container, values, times, key) {
  const g = frame(container, Math.max(...values, 1), times, (v) => String(Math.round(v)));
  const slot = g.plotW / g.n;
  const w = Math.max(2, slot - 2);           // 2px surface gap between bars
  const r = Math.min(4, w / 2);
  const base = g.y(0);
  const bars = values.map((v, i) => {
    if (!v) return null;
    const x0 = g.x(i) - w / 2;
    const top = g.y(v);
    const h = base - top;
    const rr = Math.min(r, h);
    const path = svg("path", {
      class: "bar",
      d: `M${x0},${base} V${top + rr} Q${x0},${top} ${x0 + rr},${top} H${x0 + w - rr} Q${x0 + w},${top} ${x0 + w},${top + rr} V${base} Z`,
    });
    g.root.append(path);
    return path;
  });

  // Hit targets: full-height column per second, wider than the bar itself.
  values.forEach((v, i) => {
    const hit = svg("rect", { x: g.x(i) - slot / 2, y: g.m.top, width: slot, height: g.plotH, fill: "transparent" });
    hit.addEventListener("mousemove", (e) => {
      hover[key] = i;
      bars.forEach((b, j) => b && b.classList.toggle("hover", j === i));
      showTooltip(e, [el("div", { class: "tt-time", text: times[i] || "-" }), el("div", {}, el("b", { text: String(v) }), " messages")]);
    });
    hit.addEventListener("mouseleave", () => { hover[key] = null; bars.forEach((b) => b && b.classList.remove("hover")); hideTooltip(); });
    g.root.append(hit);
  });
}

/** Two-series line chart, one shared y-axis (both are bytes/second). */
function drawLines(container, series, times, key) {
  const max = Math.max(1, ...series.flatMap((s) => s.values));
  const g = frame(container, max, times, (v) => formatBytes(Math.round(v)));

  for (const s of series) {
    const d = s.values.map((v, i) => `${i ? "L" : "M"}${g.x(i).toFixed(1)},${g.y(v).toFixed(1)}`).join(" ");
    g.root.append(svg("path", { class: `line ${s.cls}`, d }));
  }
  // Direct labels at the line ends (latest value), nudged apart if they collide.
  const last = g.n - 1;
  const ends = series.map((s) => ({ s, y: g.y(s.values[last]) }));
  if (ends.length === 2 && Math.abs(ends[0].y - ends[1].y) < 14) {
    const mid = (ends[0].y + ends[1].y) / 2;
    const up = ends[0].y <= ends[1].y ? 0 : 1;
    ends[up].y = mid - 7;
    ends[1 - up].y = mid + 7;
  }
  for (const { s, y } of ends) {
    g.root.append(svg("circle", { class: `marker ${s.cls}`, cx: g.x(last), cy: g.y(s.values[last]), r: 4 }));
    const t = svg("text", { class: "end-label", x: g.x(last) + 8, y: y + 4 });
    t.textContent = `${formatBytes(s.values[last])}/s`;
    g.root.append(t);
  }

  // Crosshair + tooltip.
  const cross = svg("line", { class: "crosshair", y1: g.m.top, y2: g.m.top + g.plotH, visibility: "hidden" });
  const markers = series.map((s) => svg("circle", { class: `marker ${s.cls}`, r: 4, visibility: "hidden" }));
  g.root.append(cross, ...markers);
  const overlay = svg("rect", { x: g.m.left, y: g.m.top, width: g.plotW, height: g.plotH, fill: "transparent" });
  overlay.addEventListener("mousemove", (e) => {
    const box = g.root.getBoundingClientRect();
    const scale = box.width / (g.m.left + g.plotW + g.m.right);
    const px = (e.clientX - box.left) / scale - g.m.left;
    const i = Math.max(0, Math.min(g.n - 1, Math.floor((px / g.plotW) * g.n)));
    hover[key] = i;
    cross.setAttribute("x1", g.x(i));
    cross.setAttribute("x2", g.x(i));
    cross.setAttribute("visibility", "visible");
    markers.forEach((mk, j) => {
      mk.setAttribute("cx", g.x(i));
      mk.setAttribute("cy", g.y(series[j].values[i]));
      mk.setAttribute("visibility", "visible");
    });
    showTooltip(e, [
      el("div", { class: "tt-time", text: times[i] || "-" }),
      ...series.map((s) => el("div", { class: "tt-row" }, el("i", { class: `sw ${s.cls}` }), `${s.name}: `, el("b", { text: `${formatBytes(s.values[i])}/s` }))),
    ]);
  });
  overlay.addEventListener("mouseleave", () => {
    hover[key] = null;
    cross.setAttribute("visibility", "hidden");
    markers.forEach((mk) => mk.setAttribute("visibility", "hidden"));
    hideTooltip();
  });
  g.root.append(overlay);
}

function renderTables(history) {
  const recent = [...history].reverse();
  const table = (head, rows) => el("table", {},
    el("thead", {}, el("tr", {}, ...head.map((h) => el("th", { text: h })))),
    el("tbody", {}, ...rows.map((r) => el("tr", {}, ...r.map((c) => el("td", { text: String(c) }))))));
  // Only rebuild while closed, so an open table doesn't jump under the reader.
  if (!$("#table-rate").closest("details").open || !$("#table-rate").firstChild) {
    $("#table-rate").replaceChildren(table(["Second", "Messages"], recent.map((h) => [h.t, h.messages])));
  }
  if (!$("#table-bytes").closest("details").open || !$("#table-bytes").firstChild) {
    $("#table-bytes").replaceChildren(table(["Second", "Bytes in", "Bytes out"], recent.map((h) => [h.t, h.bytes_in, h.bytes_out])));
  }
}

// ------------------------------------------------------- sockets + log ---

function renderConnections(s) {
  const rows = s.connection_list;
  if (!rows.length) {
    $("#conn-rows").replaceChildren(el("tr", { class: "empty-row" }, el("td", { colspan: 8, text: "No clients connected. Scan the QR code with a phone." })));
    return;
  }
  $("#conn-rows").replaceChildren(...rows.map((c) => el("tr", {},
    el("td", {}, el("div", { class: "user" }, avatar({ username: c.username, display_name: c.username }), c.username)),
    el("td", {}, el("span", { class: `proto-tag ${c.protocol}` }, el("i"), c.protocol === "ws" ? "WebSocket" : "HTTP/SSE")),
    el("td", {}, el("span", { class: `via-tag ${c.via}`, text: c.via === "internet" ? "Internet (tunnel)" : "Wi-Fi" })),
    el("td", { class: "mono", text: c.client }),
    el("td", { class: "mono", text: c.server }),
    el("td", { text: formatDuration(c.connected_for) }),
    el("td", { text: `${c.messages_in} / ${c.messages_out}` }),
    el("td", { text: c.rtt_ms === null ? "-" : `${Number(c.rtt_ms).toFixed(1)} ms` }))));
}

function renderLog(events) {
  const list = $("#log");
  // The server sends the last 30 events; redraw only when the newest one changed.
  const newest = events.length ? `${events.length}|${events[events.length - 1].time}|${events[events.length - 1].text}` : "";
  if (newest === lastLogKey && list.children.length) return;
  lastLogKey = newest;
  list.replaceChildren(...[...events].reverse().map((ev, i) =>
    el("li", { class: i === 0 ? "enter" : "" }, el("time", { text: ev.time }), el("span", { text: ev.text }))));
}
